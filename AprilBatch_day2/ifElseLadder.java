package AprilBatch_day2;

public class ifElseLadder {
	public static void main (String [] args) {
		int marks = 75;
		if(marks >= 90){
			System.out.println("A+");
		}else if(marks >= 80){
			System.out.println("A");
		}else if(marks >= 70){
			System.out.println("B+");
		}else if(marks >= 60){
			System.out.println("B");
		}else {
			System.out.println("C");
		}
	} 

}
