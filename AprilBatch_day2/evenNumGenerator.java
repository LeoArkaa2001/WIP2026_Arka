package AprilBatch_day2;

public class evenNumGenerator {
	 public static void main(String[] args) {
	        int n = 20;

	        System.out.println("Even numbers from 1 to " + n + ":");
	        for (int i = 2; i <= n; i += 2) {
	            System.out.print(i + " ");
	        }
	    }

}
